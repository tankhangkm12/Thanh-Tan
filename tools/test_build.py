"""Run with: uv run --with pyyaml --with pytest pytest tools"""

import json
import sys
from pathlib import Path

import pytest
import yaml

sys.path.insert(0, str(Path(__file__).parent))
import build  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
REAL_PLUGIN = REPO / build.DEFAULT_PLUGIN

ROLE = "---\nname: {name}\ndescription: Does {name} things.\ncapabilities: {caps}\n---\nYou are {name}.\n"


@pytest.fixture
def plugin(tmp_path) -> Path:
    root = tmp_path / "plugin"
    (root / build.ROLES_DIR).mkdir(parents=True)
    (root / ".claude-plugin").mkdir()
    (root / build.CLAUDE_MANIFEST).write_text(json.dumps({"name": "p", "version": "1.0.0"}), encoding="utf-8")
    return root


def add_role(plugin: Path, name: str, caps: str = "[read, run]") -> None:
    (plugin / build.ROLES_DIR / f"{name}.md").write_text(ROLE.format(name=name, caps=caps), encoding="utf-8")


def frontmatter(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8").split("---")[1])


def test_generates_both_variants_and_manifest(plugin):
    add_role(plugin, "tester", "[read, edit, run]")
    add_role(plugin, "reviewer")
    build.build(plugin)
    claude = frontmatter(plugin / "claude" / "agents" / "tester.md")
    assert claude == {
        "name": "tester",
        "description": "Does tester things.",
        "tools": "Read, Glob, Grep, Edit, Write, Bash, PowerShell",
        "model": "inherit",
    }
    agy = frontmatter(plugin / "agents" / "tester.md")
    assert agy["tools"] == [
        "view_file", "list_dir", "find_by_name", "grep_search",
        "write_to_file", "replace_file_content", "multi_replace_file_content", "run_command",
    ]
    manifest = json.loads((plugin / build.CLAUDE_MANIFEST).read_text(encoding="utf-8"))
    assert manifest["agents"] == ["./claude/agents/reviewer.md", "./claude/agents/tester.md"]
    assert manifest["version"] == "1.0.0"
    body = (plugin / "agents" / "tester.md").read_text(encoding="utf-8")
    assert "Generated by tools/build.py from src/roles/tester.md" in body and body.endswith("You are tester.\n")


def test_read_only_roles_get_no_edit_tools(plugin):
    add_role(plugin, "reviewer")
    build.build(plugin)
    assert "Edit" not in frontmatter(plugin / "claude" / "agents" / "reviewer.md")["tools"]
    assert not build.ANTIGRAVITY_EDIT_TOOLS.intersection(frontmatter(plugin / "agents" / "reviewer.md")["tools"])


@pytest.mark.parametrize("role", sorted(build.READ_ONLY_ROLES))
def test_read_only_role_with_edit_capability_is_refused(plugin, role):
    add_role(plugin, role, "[read, edit]")
    with pytest.raises(build.BuildError, match="read-only"):
        build.build(plugin)


@pytest.mark.parametrize(
    ("text", "message"),
    [
        ("no frontmatter", "missing '---'"),
        ("---\nname: other\ndescription: d\ncapabilities: [read]\n---\nbody", "must equal the file name"),
        ("---\nname: x\ndescription: d\ncapabilities: [fly]\n---\nbody", "fly"),
        ("---\nname: x\ndescription: d\ncapabilities: []\n---\nbody", "non-empty list"),
        ("---\nname: x\ncapabilities: [read]\n---\nbody", "description is required"),
        ("---\nname: x\ndescription: d\ncapabilities: [read]\n---\n", "prompt is empty"),
        ("---\nname: x\ndescription: d\ncapabilities: [read]\ntools: [Bash]\n---\nbody", "unknown frontmatter keys"),
    ],
)
def test_invalid_sources(plugin, text, message):
    (plugin / build.ROLES_DIR / "x.md").write_text(text, encoding="utf-8")
    with pytest.raises(build.BuildError, match=message):
        build.build(plugin)


def test_unknown_tool_name_is_refused(plugin, monkeypatch):
    add_role(plugin, "tester")
    monkeypatch.setitem(build.CLAUDE_TOOLS, build.Capability.RUN, ("Bash", "Shell"))
    with pytest.raises(build.BuildError, match="Shell"):
        build.build(plugin)


def test_check_detects_drift_and_stale_files(plugin):
    add_role(plugin, "tester")
    assert build.check(plugin)  # nothing generated yet
    build.build(plugin)
    assert build.check(plugin) == []
    (plugin / "agents" / "tester.md").write_text("edited", encoding="utf-8")
    assert build.check(plugin) == [f"out of date: {plugin / 'agents' / 'tester.md'}"]
    build.build(plugin)
    (plugin / "agents" / "ghost.md").write_text("x", encoding="utf-8")
    assert build.check(plugin) == [f"stale: {plugin / 'agents' / 'ghost.md'}"]
    build.build(plugin)
    assert not (plugin / "agents" / "ghost.md").exists()


def test_build_is_idempotent(plugin):
    add_role(plugin, "tester")
    assert build.build(plugin)
    assert build.build(plugin) == []


def test_main_exit_codes(plugin, capsys):
    add_role(plugin, "tester")
    assert build.main(["--plugin", str(plugin), "--check"]) == 1
    assert build.main(["--plugin", str(plugin)]) == 0
    assert build.main(["--plugin", str(plugin), "--check"]) == 0
    add_role(plugin, "security", "[read, edit]")
    assert build.main(["--plugin", str(plugin), "--check"]) == 1
    assert "read-only" in capsys.readouterr().err


# The real plugin ------------------------------------------------------------


def test_real_roles_follow_the_edit_rules():
    roles = {role.name: role for role in build.load_roles(REAL_PLUGIN)}
    assert set(roles) == {"orchestrator", "planner", "implementer", "tester", "security", "reviewer"}
    editors = {name for name, role in roles.items() if build.Capability.EDIT in role.capabilities}
    assert editors == {"implementer", "tester"}


def test_real_generated_files_are_up_to_date():
    assert build.check(REAL_PLUGIN) == []


def test_real_generated_agents_are_all_declared_in_the_manifest():
    manifest = json.loads((REAL_PLUGIN / build.CLAUDE_MANIFEST).read_text(encoding="utf-8"))
    declared = {Path(item).name for item in manifest["agents"]}
    on_disk = {path.name for path in (REAL_PLUGIN / build.CLAUDE_AGENTS_DIR).glob("*.md")}
    assert declared == on_disk and len(declared) == 6
    assert all(item.startswith("./") for item in manifest["agents"])


def test_tool_lists_in_real_agents_are_documented_names():
    for path in (REAL_PLUGIN / build.CLAUDE_AGENTS_DIR).glob("*.md"):
        tools = {tool.strip() for tool in frontmatter(path)["tools"].split(",")}
        assert tools <= build.CLAUDE_ALLOWED
    for path in (REAL_PLUGIN / build.ANTIGRAVITY_AGENTS_DIR).glob("*.md"):
        assert set(frontmatter(path)["tools"]) <= build.ANTIGRAVITY_ALLOWED
